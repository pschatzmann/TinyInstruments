#!/usr/bin/env python3
"""
Converts a binary sample set file (DynamicSampleSet format, e.g. the files of
the data folder) into a header which compiles the samples into the program:
the reverse of header2bin.py.

The source and the license are taken from an existing header of the same
instrument (--like), e.g. the full version.

Example:
  python3 tools/bin2header.py data/GrandPianoOctave.bin src/samples/GrandPianoOctave.h \\
      --like src/samples/GrandPiano.h
"""
import argparse
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sfz2header  # noqa: E402


def read_binary(path):
    """Reads a binary sample set (version 1 or 2): name, rate, zones"""
    raw = open(path, "rb").read()
    if raw[:4] != sfz2header.BINARY_MAGIC:
        sys.exit("not a sample set file: " + path)
    version, count, rate, data_size, name_len = struct.unpack_from("<HHIIB", raw, 4)
    if version not in (1, 2):
        sys.exit("unsupported version %d: %s" % (version, path))
    pos = 4 + struct.calcsize("<HHIIB")
    name = raw[pos:pos + name_len].decode("utf-8")
    pos += name_len
    zone_fmt = "<IIIhBBIfBBBBBBbB"
    zones = []
    for i in range(count):
        v = struct.unpack_from(zone_fmt, raw, pos)
        pos += struct.calcsize(zone_fmt)
        zones.append({
            "length": v[0], "loop_start": v[1], "loop_end": v[2], "loop_pred": v[3],
            "loop_index": v[4], "root": v[5], "decay_start": v[6], "decay_ln": v[7],
            "lokey": v[8], "hikey": v[9], "lovel": v[10], "hivel": v[11], "group": v[12],
            "off_by": v[13], "tune": v[14], "marks": [], "file": "root key %d" % v[5]})
    if version == 2:
        counts = struct.unpack_from("<%dH" % count, raw, pos)
        pos += 2 * count
        for z, n in zip(zones, counts):
            z["marks"] = list(struct.unpack_from("<%dH" % n, raw, pos))
            pos += 2 * n
    # ADPCM data: (length + 1) / 2 bytes per zone
    for z in zones:
        size = (z["length"] + 1) // 2
        z["data"] = raw[pos:pos + size]
        pos += size
    total = sum(len(z["data"]) for z in zones)
    if total != data_size or pos != len(raw):
        sys.exit("inconsistent file %s: data %d/%d, size %d/%d" % (path, total, data_size, pos, len(raw)))
    return name, rate, zones


def source_and_license(header):
    text = open(header).read()
    source = re.search(r"^// Source: (.*)$", text, re.M)
    license_text = re.search(r"^// License of the samples: (.*)$", text, re.M)
    return (source.group(1) if source else "", license_text.group(1) if license_text else "")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("binary", help="sample set file (.bin)")
    parser.add_argument("header", help="header to write (.h)")
    parser.add_argument("--like", help="header of the same instrument: source and license")
    args = parser.parse_args()
    name, rate, zones = read_binary(args.binary)
    source, license_text = source_and_license(args.like) if args.like else ("", "")
    source = "%s (%s)" % (os.path.basename(args.binary), source) if source else os.path.basename(args.binary)
    sfz2header.write_header(args.header, name, rate, zones, source, license_text)
    text = open(args.header).read().replace("// Generated by tools/sfz2header.py", "// Generated by tools/bin2header.py", 1)
    open(args.header, "w").write(text)
    print("written %s: %s, %d zones, %d bytes" % (args.header, name, len(zones),
                                                  sum(len(z["data"]) for z in zones)))


if __name__ == "__main__":
    main()
