#!/usr/bin/env python3
"""
Converts a sample set header generated by sfz2header.py into the binary file
format which can be loaded at runtime from a Stream (DynamicSampleSet), e.g.
from a file system into PSRAM.

Example:
  python3 tools/header2bin.py src/samples/GrandPiano.h data/GrandPiano.bin
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sfz2header  # noqa: E402


def parse_header(path):
    text = open(path).read()
    name = re.search(r'static const SampleSet set = \{"([^"]*)", zones, (\d+), (\d+), (\d+)\}', text)
    if not name:
        sys.exit("not a sample set header: " + path)
    datas = {}
    for m in re.finditer(r"static const uint8_t data(\d+)\[\] TI_PROGMEM = \{(.*?)\};", text, re.S):
        datas[m.group(1)] = bytes(int(v) for v in m.group(2).replace("\n", "").split(",") if v.strip())
    zones = []
    marks = {}
    for m in re.finditer(r"static const uint16_t marks(\d+)\[\] TI_PROGMEM = \{(.*?)\};", text, re.S):
        marks[m.group(1)] = [int(v) for v in m.group(2).replace("\n", "").split(",") if v.strip()]
    zone_re = (r"\{data(\d+), (\d+), (\d+), (\d+), (-?\d+), (\d+), (\d+), (\S+?)f, "
               r"(\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (-?\d+)"
               r"(?:, (?:nullptr, 0|marks(\d+), \d+))?\}")
    for m in re.finditer(zone_re, text):
        v = m.groups()
        zones.append({
            "data": datas[v[0]], "length": int(v[1]), "loop_start": int(v[2]), "loop_end": int(v[3]),
            "loop_pred": int(v[4]), "loop_index": int(v[5]), "decay_start": int(v[6]),
            "decay_ln": float(v[7]), "root": int(v[8]), "lokey": int(v[9]), "hikey": int(v[10]),
            "lovel": int(v[11]), "hivel": int(v[12]), "group": int(v[13]), "off_by": int(v[14]),
            "tune": int(v[15]), "marks": marks.get(v[16]) if v[16] else []})
    if len(zones) != int(name.group(2)):
        sys.exit("found %d zones, expected %s" % (len(zones), name.group(2)))
    return name.group(1), int(name.group(3)), zones


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    name, rate, zones = parse_header(sys.argv[1])
    sfz2header.write_binary(sys.argv[2], name, rate, zones)
    print("written %s: %d zones, %d bytes" % (sys.argv[2], len(zones), os.path.getsize(sys.argv[2])))


if __name__ == "__main__":
    main()
