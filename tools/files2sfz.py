#!/usr/bin/env python3
"""
Creates a simple SFZ mapping from sample files whose names contain the note
and the velocity layer (e.g. the VCSL sample library), so that they can be
converted with sfz2header.py.

The key ranges are split in the middle between the recorded notes and the
velocity range 1..127 is split evenly between the velocity layers.

Example (VCSL Steinway B: JHPiano_NoSus_Close_A#0_vl2_rr1.wav):
  python3 tools/files2sfz.py samples/*.wav -o grand.sfz \
      --pattern '_(?P<note>[A-G]#?-?\\d)_vl(?P<vel>\\d)_rr1' --every 2
"""

import argparse
import os
import re
import sys

NOTES = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def note_number(name):
    """Note name with octave (C4 = 60) or midi number."""
    if name.isdigit():
        return int(name)
    m = re.match(r"([A-Ga-g])([#b]?)(-?\d+)$", name)
    if not m:
        raise ValueError("invalid note: " + name)
    n = NOTES[m.group(1).upper()] + {"#": 1, "b": -1, "": 0}[m.group(2)]
    return n + (int(m.group(3)) + 1) * 12


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("files", nargs="+")
    p.add_argument("-o", "--output", required=True)
    p.add_argument("--pattern", required=True,
                   help="regex with the named groups 'note' and optionally 'vel'")
    p.add_argument("--every", type=int, default=1, help="use only every n-th recorded note")
    p.add_argument("--layers", help="comma separated velocity layer ids to use (default: all)")
    p.add_argument("--transpose", type=int, default=0,
                   help="semitones added to the note names (e.g. 12 if the names are an octave too low)")
    p.add_argument("--lokey", type=int, default=21)
    p.add_argument("--hikey", type=int, default=108)
    args = p.parse_args()

    samples = {}
    for f in args.files:
        m = re.search(args.pattern, os.path.basename(f))
        if not m:
            continue
        note = note_number(m.group("note")) + args.transpose
        vel = m.groupdict().get("vel") or "1"
        samples.setdefault(vel, {})[note] = f
    if not samples:
        sys.exit("no file matches the pattern")

    layers = sorted(samples, key=lambda v: int(v) if v.isdigit() else v)
    if args.layers:
        layers = [v for v in layers if v in args.layers.split(",")]

    out_dir = os.path.dirname(os.path.abspath(args.output))
    with open(args.output, "w") as out:
        out.write("// generated by tools/files2sfz.py\n")
        for i, layer in enumerate(layers):
            lovel = 1 + (127 * i) // len(layers)
            hivel = (127 * (i + 1)) // len(layers)
            all_notes = sorted(samples[layer])
            notes = all_notes[:: args.every]
            if notes[-1] != all_notes[-1]:
                notes.append(all_notes[-1])  # always keep the highest note
            out.write("<group> lovel=%d hivel=%d\n" % (lovel, hivel))
            for j, note in enumerate(notes):
                lo = args.lokey if j == 0 else (notes[j - 1] + note) // 2 + 1
                hi = args.hikey if j == len(notes) - 1 else (note + notes[j + 1]) // 2
                path = os.path.relpath(samples[layer][note], out_dir)
                out.write("<region> lokey=%d hikey=%d pitch_keycenter=%d sample=%s\n" % (lo, hi, note, path))
            print("layer %s: velocity %d-%d, %d notes" % (layer, lovel, hivel, len(notes)))


if __name__ == "__main__":
    main()
